"""Pure pricing engine, ported from the personal-shopper web app (TypeScript).

The app computes a published COP price from a US list price. This module is a
line-by-line port so that both implementations can be held to the same test
vectors (``tests/fixtures/parity.json``, generated by executing the TypeScript).

Source modules, in the order they appear below:

====================================  ==========================================
TypeScript                            Python
====================================  ==========================================
``lib/cotizador.ts``                   :func:`quote`
``lib/envio.ts``                       :func:`domestic_shipping`, :func:`find_zone`
``lib/settings-defaults.ts``           :func:`normalize_zones`, :data:`DEFAULT_ZONES`
``lib/comision.ts``                    :func:`commission_split`, :func:`visible_percent`
====================================  ==========================================

Nothing here does I/O. Rates, tariffs and margins arrive as parameters so the
caller decides where they come from.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any

__all__ = [
    "DEFAULT_ZONES",
    "SHIPPING_ROUNDING_COP",
    "Breakdown",
    "CommissionSplit",
    "QuoteParams",
    "Zone",
    "commission_split",
    "domestic_shipping",
    "find_zone",
    "normalize_zones",
    "quote",
    "visible_percent",
]


def _js_round(value: float, digits: int) -> float:
    """Round like JavaScript's ``Math.round``, which the source uses throughout.

    This is NOT :func:`round`. Python rounds halves to even (``round(0.125, 2)``
    is ``0.12``); JavaScript rounds halves toward +infinity (``0.13``). The web
    app has published prices computed the JavaScript way for 1,000+ real quotes,
    so the JavaScript behaviour is the specification here, not a quirk to fix.

    ``floor(x + 0.5)`` reproduces it exactly, including for negatives, where
    ``Math.round(-2.5)`` is ``-2`` rather than ``-3``.
    """
    factor = 10**digits
    return math.floor(value * factor + 0.5) / factor


def _number(value: Any) -> float:
    """Coerce like the source's ``x || 0`` guard.

    In JavaScript ``NaN || 0`` is ``0`` because NaN is falsy. In Python NaN is
    truthy and ``max(0, nan)`` is order-dependent, so a naive port silently
    propagates NaN into the price. Missing and unusable values become 0.0.
    """
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0.0
    if math.isnan(number) or math.isinf(number):
        return 0.0
    return number


