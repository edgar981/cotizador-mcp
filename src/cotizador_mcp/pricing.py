# Published price — port of lib/cotizador.ts
# ---------------------------------------------------------------------------

#: Tolerance for the final rounding step. Without it a subtotal that lands
#: exactly on a multiple can read as 500000.0000000001 and jump to the next one.
_EPSILON = 1e-9


@dataclass(frozen=True, slots=True)
class QuoteParams:
    """Inputs to :func:`quote`. Percentages are fractions: 0.25 is 25%."""

    price_usd: float
    weight_lb: float
    sales_tax_pct: float
    carrier_rate_lb_usd: float
    """Mail-forwarder tariff per pound, in USD."""
    fx_official: float
    """Official COP-per-USD rate for the day (TRM)."""
    fx_buffer_pct: float
    """Cushion over the official rate, to absorb same-day moves."""
    margin_pct: float
    """Margin over the landed COP cost."""
    rounding_cop: float
    """Round the final price up to a multiple of this. 0 disables rounding."""


@dataclass(frozen=True, slots=True)
class Breakdown:
    """What :func:`quote` returns: every intermediate value, not just the price."""

    tax_usd: float
    freight_usd: float
    landed_usd: float
    fx_applied: float
    cost_cop: float
    margin_cop: float
    subtotal_cop: float
    """Cost plus margin, before rounding."""
    price_cop: float
    """The published, rounded price."""


def quote(params: QuoteParams) -> Breakdown:
    """Compute the full breakdown for one product.

    Port of ``calcularCotizacion``. Negative or unusable inputs are clamped to
    zero rather than rejected: the web form calls this on every keystroke, so a
    half-typed value must not raise.
    """
    price_usd = max(0.0, _number(params.price_usd))
    weight_lb = max(0.0, _number(params.weight_lb))

    tax_usd = _js_round(price_usd * params.sales_tax_pct, 2)
    freight_usd = _js_round(weight_lb * params.carrier_rate_lb_usd, 2)
    landed_usd = _js_round(price_usd + tax_usd + freight_usd, 2)

    fx_applied = _js_round(params.fx_official * (1 + params.fx_buffer_pct), 2)
    cost_cop = _js_round(landed_usd * fx_applied, 2)
    margin_cop = _js_round(cost_cop * params.margin_pct, 2)
    subtotal_cop = _js_round(cost_cop + margin_cop, 2)

    step = params.rounding_cop if params.rounding_cop > 0 else 1
    # max(0, ...) keeps a subtotal of 0 from returning -0.
    price_cop = max(0.0, math.ceil(subtotal_cop / step - _EPSILON) * step)

    return Breakdown(
        tax_usd=tax_usd,
        freight_usd=freight_usd,
        landed_usd=landed_usd,
        fx_applied=fx_applied,
        cost_cop=cost_cop,
        margin_cop=margin_cop,
        subtotal_cop=subtotal_cop,
        price_cop=price_cop,
    )


# ---------------------------------------------------------------------------
# Domestic leg — port of lib/envio.ts and lib/settings-defaults.ts
# ---------------------------------------------------------------------------

#: Rounding step for the domestic leg. Deliberately NOT the published price's
#: step: rounding a shipping estimate up to the nearest 5,000 COP distorts it
#: (17,200 would become 20,000), while 500 keeps it a round number to quote.
SHIPPING_ROUNDING_COP = 500


@dataclass(frozen=True, slots=True)
class Zone:
    """One row of the domestic rate table (Bogotá to the final destination)."""

    name: str
    base_cop: float
    per_lb_cop: float


#: Starting rates, for fresh installs only. Flat (``per_lb_cop = 0``) on
#: purpose: for the light parcels this business actually ships, the carrier
#: charges practically the same regardless of weight.
DEFAULT_ZONES: tuple[Zone, ...] = (
    Zone("Bogotá", 16000, 0),
    Zone("Ciudades principales", 18500, 0),
    Zone("Resto del país", 20000, 0),
    Zone("Municipio", 20000, 0),
)


def domestic_shipping(zone: Zone, weight_lb: float) -> float:
    """``base + weight x per_lb``, rounded up to :data:`SHIPPING_ROUNDING_COP`.

    This never enters the published price. It answers a different question —
    "what does it cost to get it to my city?" — and is quoted separately.
    """
    weight = max(0.0, _number(weight_lb))
    base = max(0.0, _number(zone.base_cop))
    per_lb = max(0.0, _number(zone.per_lb_cop))

    gross = base + weight * per_lb
    # The same epsilon as the published price, for the same reason.
    return max(
        0.0,
        math.ceil(gross / SHIPPING_ROUNDING_COP - _EPSILON) * SHIPPING_ROUNDING_COP,
    )


def find_zone(zones: list[Zone] | tuple[Zone, ...], name: str | None) -> Zone | None:
    """Look a zone up by name, ignoring case and surrounding whitespace."""
    if not name or not name.strip():
        return None
    wanted = name.strip().lower()
    return next((z for z in zones if z.name.strip().lower() == wanted), None)


def normalize_zones(value: Any) -> list[Zone]:
    """Read the rate table out of untrusted JSON.

    The column has THREE meaningful states and ``None`` is semantic, not a
    mistake:

    * ``None`` (or anything that is not a list) — the row predates the feature,
      so the reference zones are returned to give the user something to edit.
    * ``[]`` — the user deleted every zone on purpose. Respected: the estimator
      stays off.
    * a populated list — the live table.

    Collapsing ``None`` into ``[]`` would erase the difference between "never
    configured" and "switched off", and the estimator would vanish for existing
    users without anyone having turned it off.
    """
    if not isinstance(value, list):
        return list(DEFAULT_ZONES)

    out: list[Zone] = []
    for item in value:
        if not isinstance(item, dict):
            continue
        raw_name = item.get("nombre", item.get("name"))
        name = raw_name.strip() if isinstance(raw_name, str) else ""
        if not name:
            continue
        base = _number(item.get("tarifa_base_cop", item.get("base_cop")))
        per_lb = _number(item.get("adicional_lb_cop", item.get("per_lb_cop")))
        if base < 0 or per_lb < 0:
            continue
        # The name is the key a saved quote stores, so it cannot repeat.
        if any(z.name.lower() == name.lower() for z in out):
            continue
        out.append(Zone(name, base, per_lb))
    return out


# ---------------------------------------------------------------------------
# Margin split — port of lib/comision.ts
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class CommissionSplit:
    commission_cop: float
    net_margin_cop: float


def commission_split(margin_cop: float, commission_pct: float) -> CommissionSplit:
    """Split the margin into commission and what is left.

    Computed over the margin, never over the published price: it divides what
    the quote earns, so the customer's price does not move. The net is derived
    by subtracting the ALREADY ROUNDED commission, so the two lines add up to
    the margin exactly.
    """
    margin = max(0.0, _number(margin_cop))
    pct = max(0.0, _number(commission_pct))

    commission = _js_round(margin * pct, 2)
    return CommissionSplit(commission, _js_round(margin - commission, 2))


def visible_percent(fraction: float) -> float:
    """0.1 -> 10, for display. Drops floating-point noise."""
    return _js_round(_number(fraction) * 100, 2)
