"""Every vector in parity.json must come out of Python exactly as it came out of
TypeScript.

The fixture is generated by executing the web app's own modules
(``tools/generar-parity.ts``), so these are not transcribed expectations: they
are what production actually computes. Comparison is exact — both sides do the
same double arithmetic, so "close enough" would only hide a real divergence.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from cotizador_mcp.pricing import (
    QuoteParams,
    Zone,
    commission_split,
    domestic_shipping,
    find_zone,
    normalize_zones,
    quote,
    visible_percent,
)

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "parity.json").read_text())


def _ids(cases: list[dict[str, Any]], key: str = "nombre") -> list[str]:
    return [str(c.get(key, i)) for i, c in enumerate(cases)]


def _zone(raw: dict[str, Any]) -> Zone:
    return Zone(raw["nombre"], raw["tarifa_base_cop"], raw["adicional_lb_cop"])


def _as_float(value: Any) -> float:
    """The generator writes NaN as a string, since JSON has no NaN literal."""
    return float("nan") if value == "NaN" else float(value)


def test_fixture_declares_its_source() -> None:
    """A fixture without a commit cannot be re-checked against the source."""
    source = FIXTURE["_fuente"]
    assert len(source["commit"]) == 40
    assert source["repo"] == "cotizador-personal-shopper"


@pytest.mark.parametrize(
    "case", FIXTURE["calcular_cotizacion"], ids=_ids(FIXTURE["calcular_cotizacion"])
)
def test_quote(case: dict[str, Any]) -> None:
    entrada = case["entrada"]
    got = quote(
        QuoteParams(
            price_usd=_as_float(entrada["precio_usd"]),
            weight_lb=_as_float(entrada["peso_lb"]),
            sales_tax_pct=entrada["sales_tax_pct"],
            carrier_rate_lb_usd=entrada["tarifa_lb_usd"],
            fx_official=entrada["trm_oficial"],
            fx_buffer_pct=entrada["trm_buffer_pct"],
            margin_pct=entrada["margen_pct"],
            rounding_cop=entrada["redondeo_cop"],
        )
    )
    want = case["esperado"]
    assert got.tax_usd == want["tax_usd"]
    assert got.freight_usd == want["flete_usd"]
    assert got.landed_usd == want["aterrizado_usd"]
    assert got.fx_applied == want["trm_aplicada"]
    assert got.cost_cop == want["costo_cop"]
    assert got.margin_cop == want["margen_cop"]
    assert got.subtotal_cop == want["subtotal_cop"]
    assert got.price_cop == want["precio_cop"]


@pytest.mark.parametrize(
    "case", FIXTURE["calcular_envio_nacional"], ids=_ids(FIXTURE["calcular_envio_nacional"])
)
def test_domestic_shipping(case: dict[str, Any]) -> None:
    assert domestic_shipping(_zone(case["zona"]), case["peso_lb"]) == case["esperado"]


@pytest.mark.parametrize(
    "case", FIXTURE["buscar_zona"], ids=_ids(FIXTURE["buscar_zona"], "nombre_buscado")
)
def test_find_zone(case: dict[str, Any]) -> None:
    got = find_zone([_zone(z) for z in case["zonas"]], case["nombre_buscado"])
    want = case["esperado"]
    assert (got is None) == (want is None)
    if want is not None:
        assert got == _zone(want)


@pytest.mark.parametrize("case", FIXTURE["normalizar_zonas"], ids=_ids(FIXTURE["normalizar_zonas"]))
def test_normalize_zones(case: dict[str, Any]) -> None:
    entrada = case["entrada"]
    assert normalize_zones(None if entrada == "__undefined__" else entrada) == [
        _zone(z) for z in case["esperado"]
    ]


@pytest.mark.parametrize(
    "case", FIXTURE["calcular_comision"], ids=_ids(FIXTURE["calcular_comision"])
)
def test_commission_split(case: dict[str, Any]) -> None:
    got = commission_split(case["margen_cop"], case["comision_pct"])
    assert got.commission_cop == case["esperado"]["comision_cop"]
    assert got.net_margin_cop == case["esperado"]["margen_neto_cop"]


@pytest.mark.parametrize(
    "case", FIXTURE["porcentaje_visible"], ids=_ids(FIXTURE["porcentaje_visible"], "fraccion")
)
def test_visible_percent(case: dict[str, Any]) -> None:
    assert visible_percent(case["fraccion"]) == case["esperado"]


def test_commission_lines_always_add_up() -> None:
    """Property the web app relies on: the two lines must reconstruct the margin."""
    for margin in (0.3, 125052, 80000, 1234567.89, 0.05, 999.99):
        for pct in (0, 0.075, 0.1, 0.5, 1):
            split = commission_split(margin, pct)
            assert round(split.commission_cop + split.net_margin_cop, 2) == round(margin, 2)
